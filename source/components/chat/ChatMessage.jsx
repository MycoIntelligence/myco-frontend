import React from "react";

export default function ChatMessage({ sender, text, time, clarifications, onSelectQuestion, assistantName = "Myco Assistant" }) {
  const isUser = sender === "user";

  return (
    <div className={`myco-chat-msg ${isUser ? "myco-chat-msg--user" : "myco-chat-msg--bot"}`}>
      {!isUser && (
        <div className="myco-chat-msg-header">
          <span className="myco-chat-msg-author">{assistantName}</span>
          <span className="myco-chat-ai-badge" title="Generated by AI">AI</span>
        </div>
      )}
      <div className="myco-chat-bubble">
        {text}
        {clarifications && clarifications.length > 0 && (
          <div className="myco-chat-suggestions" style={{ marginTop: "8px" }}>
            {clarifications.map((faq) => (
              <button
                key={faq.id}
                type="button"
                className="myco-chat-pill"
                onClick={() => onSelectQuestion(faq.question)}
              >
                {faq.question}
              </button>
            ))}
          </div>
        )}
      </div>
      {time && <span className="myco-chat-time">{time}</span>}
    </div>
  );
}
